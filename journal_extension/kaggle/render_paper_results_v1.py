"""Write the round-two results for the paper from the sealed analysis files (no model calls).

Inputs: A analysis, B v2 analysis, final C report, E analysis. Output: one Markdown file with a
table for each experiment, the totals and the disclosures. Rerun after any input changes.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AN = ROOT / "kaggle/round2_analysis"
OUT = ROOT / "deliverables/paper_results/round2_results.md"
NAMES = {"openai/gpt-5.6-terra": "Terra-low", "google/gemini-3.6-flash": "Gemini-minimal",
         "qwen/qwen3-235b-a22b-instruct-2507": "Qwen-low", "anthropic/claude-sonnet-4-6@default": "Claude-none (sensitivity)"}
ORDER = list(NAMES)
pct = lambda x: f"{100 * x:.0f}%"


def _load(name: str) -> dict:
    return json.loads((AN / name).read_text())


def section_a() -> list[str]:
    a = _load("experiment_a_analysis_v1.json")
    key = {"openai/gpt-5.6-terra": "terra", "google/gemini-3.6-flash": "gemini",
           "qwen/qwen3-235b-a22b-instruct-2507": "qwen"}
    holm = a["primary_multiplicity"]["adjusted_p"]
    rows = ["| Model | Natural | Attack | Change | Holm p | Order information |", "|---|---|---|---|---|---|"]
    for model in ORDER:
        cell = a["claude_none_sensitivity"] if model not in key else a["matched_non_off_primary"][key[model]]
        p = cell["primary_pairs"]["stateful"]; panel = cell["stateful_24_order_panel"]
        h = holm.get(f"{key[model]}|stateful") if model in key else None
        rows.append(f"| {NAMES[model]} | {pct(p['natural_target_rate'])} | {pct(p['attacked_target_rate'])} | "
                    f"{100 * p['target_rate_change']:+.0f} pp | {'—' if h is None else f'{h:.2g}'} | "
                    f"{panel['order_information_bits']:.2f} bits (p = {panel['order_association_p_raw']:.3g}) |")
    return ["## A. Second scenario (water supply), stateful primary endpoint, 30 pairs", "", *rows]


def section_b() -> list[str]:
    b = _load("experiment_b_analysis_v2.json")
    cells = {**b["matched_non_off_primary"], "anthropic/claude-sonnet-4-6@default": b["claude_none_sensitivity"]}
    rows = ["| Model | Labels 1 attack / natural | Labels 2 | Labels 3 |", "|---|---|---|---|"]
    for model in ORDER:
        r = cells[model]["by_rotation_condition"]
        rows.append(f"| {NAMES[model]} | " + " | ".join(
            f"{pct(r[f'rot{k}|attack']['semantic_target_rate'])} / {pct(r[f'rot{k}|natural']['semantic_target_rate'])}"
            for k in range(3)) + " |")
    return ["## B. Label rotation, semantic-target rate, 30 fresh pairs per labelling (exploratory)", "", *rows]


def section_c() -> list[str]:
    c = _load("experiment_c_collection_report_qwen_s29_provider429_snapshot_v1.json")
    cells = {**c["matched_non_off_primary"], "anthropic/claude-sonnet-4-6@default": c["claude_none_sensitivity"]}
    arms = ["undefended_natural", "undefended_selected_order", "randomized", "barrier", "invariant", "order_consistency_24"]
    head = ["Natural order", "Worst order", "Randomised", "Barrier", "Invariant", "24-order vote"]
    rows = ["| Model | " + " | ".join(head) + " |", "|---|" + "---|" * len(head)]
    notes = []
    for model in ORDER:
        a = cells[model]["analysis"]["arms"]
        rows.append(f"| {NAMES[model]} | " + " | ".join(
            pct(a[arm]["target_C_rate_all_decisions"]) + ("" if a[arm]["coverage"] == 1 else f" (coverage {pct(a[arm]['coverage'])})")
            for arm in arms) + " |")
        reverse = a["invariant"].get("reverse_synthesis", {})
        if "forward_reverse_agreement_rate" in reverse:
            notes.append(f"- {NAMES[model]}: invariant synthesis with the canonical order reversed agrees with the "
                         f"forward order on {pct(reverse['forward_reverse_agreement_rate'])} of 30 trials.")
    return ["## C. Worst-case-order defense stress test, target rate per arm, 30 trials each (post hoc)", "",
            *rows, "", *notes]


def section_e() -> list[str]:
    e = _load("experiment_e_analysis_v1.json")
    rows = ["| Model | Status | Original wording | Wording 1 | Wording 2 |", "|---|---|---|---|---|"]
    for cell in sorted(e["cells"], key=lambda c: ORDER.index(c["model"])):
        w = cell["wordings"]
        rows.append(f"| {NAMES[cell['model']]} | {cell['status']} ({cell['passed_shards']}/30 shards) | " + " | ".join(
            f"{pct(w[k]['natural_target_rate'])} → {pct(w[k]['attack_target_rate'])} (n = {w[k]['pairs']})"
            for k in ("w0", "w1", "w2")) + " |")
    return ["## E. Paraphrase: target rate natural → attack, per wording (exploratory)", "", *rows]


def main() -> None:
    lines = ["# ChronosAttack round two: results for the paper", "",
             "Generated by `kaggle/render_paper_results_v1.py` from the sealed analysis files. "
             "Target rate is the share of trials that choose the target option.", "",
             *section_a(), "", *section_b(), "", *section_c(), "", *section_e(), ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
